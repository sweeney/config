-- Record the actor's username alongside their identity subject.
--
-- The sub is the stable key and stays authoritative. The username is the
-- human label, stored rather than resolved at read time for two reasons.
-- An audit trail should not need identity to be reachable in order to be
-- legible, and it should not change meaning when someone is renamed or their
-- account is deleted — it records what was true at the time, which is the
-- whole point of keeping one.
--
-- Nullable, and deliberately not backfilled: rows written before this column
-- existed genuinely do not know the username, and asking identity for the
-- current name of that sub today would record a present-day fact as a
-- historical one. Readers fall back to the sub.
--
-- ALTER TABLE ADD COLUMN is the one migration shape common/db handles
-- natively without a guard clause. Since common/v0.6.0 the runner records
-- applied migrations in a schema_migrations ledger, so this file is offered
-- once and then never again. On the upgrade boot of a database that predates
-- the ledger it is re-run once to adopt it, and the resulting
-- "duplicate column name" is skipped for this statement alone.
--
-- Keep the prose in this file free of semicolons anyway. A pre-v0.6.0 binary
-- splits a migration on semicolons with no awareness of comments, so one in
-- this sentence would cut it in half and leave a remainder that does not
-- parse. Rolling back to the previous binary is supported and documented as
-- safe in docs/deployment.md, and that is what still depends on this: the
-- constraint outlives the runner that originally imposed it.
--
-- Do not edit this file once it has shipped, comments included. The ledger
-- records a checksum per migration and warns on every boot when a deployed
-- database's recorded checksum no longer matches. See docs/deployment.md.
ALTER TABLE config_audit ADD COLUMN actor_username TEXT;
